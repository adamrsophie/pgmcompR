test_that("custom inference methods and scores can be registered", {
  register_inference_method("ve_copy", function(model, variables, evidence, ...) query(model, variables, evidence, method = "ve"))
  on.exit(unregister_extension("inference", "ve_copy"))
  bn <- example_network("asia")
  expect_equal(query(bn, "lung", list(xray = "yes"), method = "ve_copy"), query(bn, "lung", list(xray = "yes")))
  expect_error(register_inference_method("ve_copy", identity), "already exists")
  expect_error(unregister_extension("inference", "ve"), "Built in")
  expect_true("ve_copy" %in% list_extensions()$inference)
  register_score("edges_penalty", function(node, parents, data, ...) -length(parents))
  on.exit(unregister_extension("score", "edges_penalty"), add = TRUE)
  d <- simulate_bn(example_network("sprinkler"), 200, seed = 1)
  expect_identical(nrow(hill_climb(d, score = "edges_penalty")$edges), 0L)
  expect_error(query(bn, "lung", method = "nope"), "Unknown inference method")
})

test_that("custom CPD classes follow the contract", {
  logistic_cpd <- function(child, parent, a, b) structure(list(child = child, parents = parent, a = a, b = b), class = "logistic_cpd")
  registerS3method("cpd_to_factor", "logistic_cpd", function(x, model, ...) {
    p1 <- plogis(x$a + x$b * c(0, 1))
    cpd(x$child, rbind(1 - p1, p1), parents = x$parents, states = list(B = c("0", "1"), A = c("0", "1")))
  }, envir = asNamespace("pgmcompR"))
  bn <- bayesian_network(list(c("A", "B")), states = list(A = c("0", "1"), B = c("0", "1")))
  bn <- add_cpd(bn, cpd("A", c(`0` = 0.5, `1` = 0.5)))
  bn <- add_cpd(bn, logistic_cpd("B", "A", -1, 2))
  q <- query(bn, "B")
  expect_equal(factor_values(q)[2], 0.5 * plogis(-1) + 0.5 * plogis(1))
  s <- simulate_bn(bn, 100, seed = 1)
  expect_identical(nrow(s), 100L)
})
